    puts("  inputType : String");
    puts("  outputType : String");
    puts("  nodesBefore : Nat");
    puts("  nodesAfter : Nat");
    puts("  mapNodesFused : Nat");
    puts("  fnChainCount : Nat");
    puts("  idempotentEliminated : Nat");
    puts("  propertyBlocked : Nat");
